type CardSeed = readonly [id: string, emoji: string, word: string, subcategory: string]

function createCards(
  category: string,
  seeds: readonly CardSeed[],
  colors: Pick<CAACard, "bgColor" | "textColor" | "borderColor">,
): CAACard[] {
  return seeds.map(([id, emoji, word, subcategory], order) => ({
    id,
    emoji,
    word,
    category,
    subcategory,
    categoryId: category,
    subcategoryId: subcategory,
    favorite: false,
    custom: false,
    order,
    ...colors,
  }))
}

